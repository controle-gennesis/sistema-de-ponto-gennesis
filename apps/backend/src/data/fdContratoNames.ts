/** Nome do contrato legado pelo ID da planilha (case-insensitive). */
export function fdContratoName(externalId: string | null | undefined): string | null {
  const key = String(externalId || '').trim();
  if (!key) return null;
  if (FD_CONTRATO_NAMES[key]) return FD_CONTRATO_NAMES[key]!;
  const lower = key.toLowerCase();
  for (const [id, name] of Object.entries(FD_CONTRATO_NAMES)) {
    if (id.toLowerCase() === lower) return name;
  }
  return null;
}
